; ASSEMBLER CODE: INTEL 8051 device STC15W104
; SDCC SDAS8051 ASSEMBLER
; BIT_BANG UART     8 bit data, no-parity, 1 stop bit, 19200 baud, Interrupt Driven
; Timer 0 Data Reception
; Timer 2 Data Transmission

.module bb_uart_drv

.optsdcc -mmcs51 --model-small -iram-size 128 --xram-size 0 --code-size 4088

.include "stc15w-sdcc.inc"			; STC15W104 Processor header file

;-----------------------------------------------------------------------
; Software UART
;-----------------------------------------------------------------------
MPU_CLK_HZ	.EQU		22118000			; 22.118MHz, 30.041 MHz Max
CLKDV		.EQU		1					; system clock No divide
CLKDV12		.EQU		12					; system clock divide 12

SW_RX		.EQU		P3.0				; MCU_RxD(P3.0), SW UART RX GPIO pin (must be /INT4)
SW_TX		.EQU		P3.1				; MCU_TxD(P3.1), SW UART TX GPIO pin (can be any GPIO pin)
;
BAUD		.EQU		19200			; baud rate, 1152	;19200bps @ 22.1184MHz 1146 tick
BAUD_RATE	.EQU		((MPU_CLK_HZ/CLKDV)/BAUD)	; (FOSC/CLKDV/BAUD), SYSCLK_FREQ/DIV/BAUD_RATE
;
TX_CORR		.EQU		0				; Timer preload correction value in cycles for TX, should only offset the start bit
RX_CORR		.EQU		0				; Timer preload correction value in cycles for RX, should only offset the start bit
THALF_CORR	.EQU		51				; Timer preload correction value for 3/2 RX, machine cycles
										; Start-Bit is asynchronously generated by INT4. INT4 to mid-bit is firmware
;
; Timer0 is the Recive Clock, started on /INT4 runs asynchronously
; Timer2 is the Transmit Clock, runs synchronously
TXBAUD		.EQU		(65536-(BAUD_RATE-TX_CORR))	; actual 16-bit bit counter cycle value  TX
RXBAUD		.EQU		(65536-(BAUD_RATE-RX_CORR))	; actual 16-bit bit counter cycle value  RX
RXBAUD_HLF	.EQU		(65536-(BAUD_RATE+(BAUD_RATE/2)-THALF_CORR))	; 1.5 bit time + adjusted for process delay
;
; SWSCON: Software Serial Port Control (Bit-Addressable) Register
SWSCON		.EQU		0x20				; Serial Port Control Register
; Bits
SWRI		.EQU		0x00			; Receive interrupt flag, set on 8th RX BIT in, cleared by software.
SWTI		.EQU		0x01			; Transmit interrupt flag, set on 8th TX BIT out, cleared by software.
SWBRK		.EQU		0x02			; RX break signal
SWBFF		.EQU		0x03			; RX buffer overflow
SWREN		.EQU		0x04			; (0) Enables serial reception.
SRXBSY		.EQU		0x05			; Receiver Busy. "SWSM0"
STXBSY		.EQU		0x06			; Transmitter Busy. "SWSM1"
SWFE		.EQU		0x07			; Framing Error BIT, should be cleared by software. SM2 on write
;
; UART BYTE BUFFER
RXBIN		.EQU		0x30			; RX BIT accumulator
RXDATA		.EQU		0x31			; RX Data Buffer
TXBIN		.EQU		0x32			; TX BIT decimator
TXDATA		.EQU		0x33			; TX Data Buffer
;
; UART STATE MACINE
SURXST		.EQU		0x34			; receiver state, BIT count
SUTXST		.EQU		0x35			; transmitter state, BIT count
;
; UART RX RING BUFFER
RXBUFFER	.EQU		0x40			; 0x40 - 0x4F Receive Buffer
RXBUFEND	.EQU		(RXBUFFER+0x0F)	; buffer end 16(0x0F)/32(0x1F) bytes
;

;=======================================================
; Interrupt Vectors Table (ABS addresses 0x0000-0x002B)
;=======================================================
.area VECTOR    (CODE)
.area INTV (ABS)				; allow .org defines

		;; --- Rest Vector  ---
		.ORG    0x0000
		LJMP    _START

		;; --- Externa 0 Interrupt (INT0) ---
		.area INT0 (ABS,CODE)
		.ORG    0x0003
		RETI

		;; --- Timer 0 Interrupt (TF0) ---
		.area TMR0 (ABS,CODE)
		.ORG    0x000B
		LJMP	_TIMER0_ISR

		;; --- Externa 1 Interrupt (INT1) ---
		.area INT1 (ABS,CODE)
		.ORG    0x0013
		;LJMP	_EXT1_ISR
		RETI

		;; --- Externa 2 Interrupt (INT2) ---
		.area INT2 (ABS,CODE)
		.ORG    0x0053
		RETI

		;; --- Externa 3 Interrupt (INT3) ---
		.area INT3 (ABS,CODE)
		.ORG    0x005B
		;LJMP	_EXT3_ISR
		RETI

		;; --- Timer 2 Interrupt (TF0) ---
		.area TMR2 (ABS,CODE)
		.ORG    0x0063      ; Timer 2
		LJMP   _TIMER2_ISR

		;; --- Externa 4 Interrupt (INT4) ---
		.area INT4 (ABS,CODE)
		.ORG    0x0083
		LJMP   _INT4_ISR


; ============================================================
;				MAIN PROGRAM CODE
; ============================================================
.AREA CSEG (ABS,CODE) ; ABSOLUTE ADDRESS, debugging
.ORG 0X0100

_START:

			; INITIALIZE STACK POINTER
			MOV SP, 	#0x60           ; set stack pointer STACK TEST, 32 byte stack
			ANL	PSW,	#(~0x18)		; Bank zero(0)

			ACALL	UART_INIT			; bit-bang uart configuration

_START00:	

			ACALL	RX_BLIND			; call is blocking
			
			
			; echo back data
			MOV	TXDATA,RXDATA				
			ACALL	TX_TRANSMIT
			JC	(.-2)						; wait for completion, STXBSY clear


			SJMP	_START00



;=======================================================================
;				UART BIT BANG DRIVER
;=======================================================================


;========================================================================
;						UART INITIALIZATION
;========================================================================
UART_INIT:
			; SW_RX		.EQU		P3.0				; MCU_RxD(P3.0), SW UART RX GPIO pin (must be /INT4)
			; SW_TX		.EQU		P3.1				; MCU_TxD(P3.1), SW UART TX GPIO pin (can be any GPIO pin)
			; P3M1[7 : 0]	P3M0 [7 : 0]
			; 		1			0			P3.0 input-only (high-impedance )
			;MOV	P3M1,	#0b00000001			;
			;MOV	P3M0,	#0b00000000			;

			; Serial Port Control Register
			SETB	SW_TX					; set TX output MARK
			; SWSCON
			CLR	SWRI						; Receive interrupt flag, set on 8th RX BIT in, cleared by software.
			CLR	SWTI	                    ; Transmit interrupt flag, set on 8th TX BIT out, cleared by software.
			CLR	SWBRK	                    ; RX break signal
			CLR	SWBFF	                    ; RX buffer overflow
			CLR	SWREN	                    ; Enables serial reception(1). Transmission (0)
			CLR	SRXBSY	                    ; Receiver Busy. "SWSM0"
			CLR	STXBSY	                    ; Transmitter Busy. "SWSM1"
			CLR	SWFE                        ; Framing Error BIT, should be cleared by software. SM2 on write

			;--------------- Configure System Clock Source -------------
			; configure system clock source
			ANL CLK_DIV,	#(~(CLKS2|CLKS1|CLKS0))			; set system clock divider/1

			;------------------ Configure Timer 0 ---------------------- straight from the manual
			;ORL		IP,		#PT0			; set timer(0) high priority IRQ
			ORL		AUXR,	#0x80			; T0x12, Timer 0 in 1T mode
			MOV		TMOD, 	#0x00			; set Timer0 in mode 0(16 bit auto-reloadable mode)
			ANL		TMOD,	#0xFB			; C/T0=0, count on internal system clock
			MOV	TH0, #(RXBAUD_HLF >> 8)		; load 1.5 bit time (we assume the start bit is good)
			MOV	TL0, #(RXBAUD_HLF & 0xFF)	; Timer0 will interrupt on center of next bit time
			CLR		TR0						; STOP, Timer/Counter 0 Run Control BIT, (Bit-Addressable)
			CLR		ET0						; disable Timer0 IRQ

			;------------------ Receive Ring Buffer -------------------------
			;MOV	RXHEAD,	#RXBUFFER			; received data pointers
			;MOV	RXTAIL,	#RXBUFFER
			;MOV	RXCNT,	#0x00				; buffer byte count

			;------------------ INT4 -----------------------------------
			ANL		AUXR2,	#(~EX4)			; disable interrupts on INT4 port


			;------------------ Configure Timer 2 -------------------------
			; set-up Timer 2 and INT4
			ANL		AUXR,	#(~T2R)			; Timer2 stop

			MOV		T2H,	#(RXBAUD>>8)	; Data Bits
			MOV		T2L,	#(RXBAUD&0xFF)	;

			ORL		AUXR,	#T2x12			; T2 in 1T mode, set 1 the clock source of Timer 2 is SYSCLK/1

			; Asynchronous Timer2   ; enable the 3 next lines to set timer2 free running with system ticks
			;ORL	AUXR,	#T2R				; T2 start to run
			;ORL	IE2,	#ET2				; enable T2 interrupt
			MOV	SUTXST, #0x09				; in asynchronous Timer2 mode, leave TX State in IDLE, end of transmission

			SETB	EA						; Go Live!

			RET


;=======================================================================
; 						OPEN, ALLOW UART RECEPTION
; Allow receive data to be buffered, 16 bytes max, with overflow detection
;=======================================================================
RX_OPENBUFF:
			; set receive state variables
			SETB	SWREN					; RX mode, run
			CLR		SWRI					; no data available
			CLR		SWFE					; clear framing error
			CLR		SWBRK					; clear line break

			; enable INT4
			ORL	AUXR2,	#EX4				; enable INT4 interrupt, AUXR2
			; INT4 is re-enabled at the end of each byte received.

			RET

;=======================================================================
;				CLOSE, DISABLE UART RECEPTION
;=======================================================================
RX_CLOSEBUFF:
			; set receive state variables
			CLR		SWREN					; RX mode, run

			; disable INT4, halt RX reception
			ANL	AUXR2,	#(~EX4)				; disable INT4 interrupt, AUXR2

			CLR		TR0						; STOP, Timer/Counter 0 Run Control BIT, (Bit-Addressable)
			CLR		ET0						; disable Timer0 IRQ

			RET

;=======================================================================
; 						RX SIMPLE RECEIVE
;=======================================================================
RX_BLIND:	; Receive Blocking

			; set receive state variables
			SETB	SWREN					; RX mode
			CLR		SWRI					; no data available
			CLR		SWFE					; clear framing error
			CLR		SWBRK					; clear line break

			; enable INT4
			ORL	AUXR2,	#EX4				; enable INT4 interrupt, AUXR2

RECEIVE_WAIT:								; retrieve data byte
			; WAIT, SWRI WILL COMPLETE, if there was a start bit
			JNB	SWRI, RECEIVE_WAIT			; no data available
			JB	SRXBSY,	RECEIVE_WAIT		; receiver busy

			; disable INT4
			ANL	AUXR2,	#(~EX4)				; disable INT4 interrupt, AUXR2,

			MOV	A,	RXDATA					; return data

			SETB	C
			JB	SWBRK,	RX_FEBREAK			; indicate error state
			JB	SWFE,	RX_FEBREAK			; clear flags at application level
			CLR		C						; no errors
RX_FEBREAK:

			RET




;=======================================================================
;					UART RECEIVER INTERRUPT SERVICE INT4 & TIMER 0
;=======================================================================
_INT4_ISR:
			ANL     AUXR2,	#(~EX4)			; Disable INT4
			MOV		SURXST,	#0x00			; start-bit state (0) RECPTION

_TIMER0_ISR:
			PUSH	PSW						; resource preservation
			PUSH	ACC
			PUSH	B
			PUSH	0x00					; R0 bank(0)

			PUSH	DPH						; resource preservation
			PUSH	DPL

SWRX_PROCESS_STATE:

			MOV	A, SURXST					; read state offset from table
			MOV	DPTR, #SWRX_STATE_TABLE
			MOVC	A, @A+DPTR				; 'A' now contains state offset (PC)
			JMP	@A+DPTR						; execute state

TIMER0_ISR_RXEND:							; ALL TX/RX states return here

			POP	DPL							; resource restoration
			POP	DPH

			POP	0x00						; R0 bank(0)
			POP	B
			POP	ACC							; resource restoration
			POP	PSW
			RETI

;-----------------------------------------------------------------------------
; RX STATE MACHINE
;-----------------------------------------------------------------------------
SWRX_STATE_TABLE:							; each table entry is 1 byte
	.DB		SWRX_S0 - SWRX_STATE_TABLE		; idle / start detect
	.DB		SWRX_S1 - SWRX_STATE_TABLE		; b0
	.DB		SWRX_S2 - SWRX_STATE_TABLE		; b1
	.DB		SWRX_S3 - SWRX_STATE_TABLE		; b2
	.DB		SWRX_S4 - SWRX_STATE_TABLE		; b3
	.DB		SWRX_S5 - SWRX_STATE_TABLE		; b4
	.DB		SWRX_S6 - SWRX_STATE_TABLE		; b5
	.DB		SWRX_S7 - SWRX_STATE_TABLE		; b6
	.DB		SWRX_S8 - SWRX_STATE_TABLE		; b7
	.DB		SWRX_S9 - SWRX_STATE_TABLE		; stop bit
	.DB		SWRX_S10 - SWTX_STATE_TABLE		; stop bit terminus/break

;-----------------------------------------------------------------------
;SWRX_S0: RX IDLE state, falling edge has been detected on /INT4.
;-----------------------------------------------------------------------
SWRX_S0:
			; START-BIT, INT4 disabled in _INT4_ISR

			JNB	SWREN, SWRX_S0_END			; (5) Check to see if SW UART RX is enabled, else remain at IDLE state

			CLR	TR0							; (3) Stop TX Timer0 stop, clears any pending interrupt.
			ORL	AUXR,	#T0x12				; (3) T0x12, set 1 : clock source of Timer 0 is SYSclk/1.

			MOV	TH0, #(RXBAUD_HLF >> 8)		; (3) load 1.5 bit time (we assume the start bit is good)
			MOV	TL0, #(RXBAUD_HLF & 0xFF)	; (3) Timer0 will interrupt on center of next bit

			SETB	TR0						; (3) T0 start to run, next access reload_register
											; (20) cycles, bit timing correction...

			MOV	TH0, #(RXBAUD >> 8)			; (3) reload-register 1 bit time (used on next timer 2 reload)
			MOV	TL0, #(RXBAUD & 0xFF)		; (3)

			SETB	ET0						; (3) allow Timer0 to interrupt
			SETB	EA						; (3) enable global interrupts

			INC	SURXST						; (3) next state is SWRX_S1 (we assume START bit was good)

			JB	SW_RX,	SWRX_S0_ABORT		; (5) false start-bit, reset if start bit went MARK in this state, abort!

			SETB	SRXBSY					; good start bit

SWRX_S0_END:
			AJMP	TIMER0_ISR_RXEND

SWRX_S0_ABORT:
			CLR	TR0							; Stop TX Timer0 stop
			CLR	ET0							; disable Timer0 interrupt
			ORL		AUXR2,	#EX4			; restart INT4 interrupt
			AJMP	TIMER0_ISR_RXEND

;-----------------------------------------------------------------------
;SWRX_S1 through SWRX_S8: capture b0..b7
;-----------------------------------------------------------------------
SWRX_S1:
SWRX_S2:
SWRX_S3:
SWRX_S4:
SWRX_S5:
SWRX_S6:
SWRX_S7:
SWRX_S8:
			MOV	C, SW_RX					; Move RX state into Carry prior to rshift
			MOV	A, RXBIN
			RRC	A							; right shift Carry into shift register
			MOV	RXBIN, A					; re-store

			INC	SURXST						; advance state variable

SWRX_S2_END:

			AJMP	TIMER0_ISR_RXEND

;------------------------------------------------------------------------------------
; STOP BIT, Framing Error  Detection if-then Break Detection
;------------------------------------------------------------------------------------
SWRX_S9:

			MOV	RXDATA, RXBIN				; move received data byte into temp buffer

			;; move data to buffer
			;MOV	R0,	RXPTR
			;MOV	@R0, RXBIN
			;INC	RXPTR
			;;INC RXCNT						;
			;;ANL	RXCNT, #0x0F				; wrap count
			;ANL	RXPTR,	#0x4F				; wrap pointer

			CLR	SWFE						; cleared by software
			JB	SW_RX, S9_RXEND				; RX is MARK (1), valid stop
			SETB	SWFE					; flag Framing Error
			INC	SURXST						; test for break command

			AJMP	TIMER0_ISR_RXEND		; No stop bit, next state check for break

S9_RXEND:									; good stop bit

			CLR	TR0							; Timer0 stop
			CLR	ET0							; disable Timer0 to interrupt

			; stop bit is in MARK, safe to enable hardware INT4
			ORL	AUXR2,	#EX4				; enable interrupts on INT4, for next byte
			;SETB	EA						; enable global IRQs, already enabled

			; ready to receive next byte,
			SETB	SWRI					; set receive flag, data available
			MOV	SURXST,	#0					; set IDLE state
			CLR	SRXBSY						; Receiver idle


			AJMP	TIMER0_ISR_RXEND

;------------------------------------------------------------------------------------
; RX BREAK, FLAG AND WAIT
;------------------------------------------------------------------------------------
SWRX_S10:										; Break Command

			JNB	SW_RX, S10_WAIT					; RX is SPACE, WAIT!

			; RX now MARK, evaluate
			MOV	A,	RXBIN
			JNZ	S10_SWFE						; data not zero, Frame Error

			SETB	SWBRK						; set flag break
S10_SWFE:
			SJMP	S9_RXEND					; normal exit, reset for next RX character

S10_WAIT:
			AJMP	TIMER0_ISR_RXEND			; Repeat S11 state until RX returns to MARK!



;=======================================================================
;  TX UART TRANSMISSION
;=======================================================================
; NOTE: Transmission uses Timer(2) asynchronous clock with NO system ticks

;=======================================================================
; 						TRANSMIT ONE BYTE
;=======================================================================
TX_TRANSMIT:

			SETB	C						; set error, cleared if routine runs OK
			;JB	SWREN,	TX_TRANSMIT_EXIT	; not in transmit mode
			JB	STXBSY,	TX_TRANSMIT_EXIT	; TX already busy, can not transmit, IRQ

			;ANL	AUXR2,	#(~EX4)				; disable INT4, receiver

			SETB	STXBSY					; indicate TX busy
			CLR	SWTI						; TX data not ready
			;CLR	SWREN						; enter transmit mode

			MOV	TXBIN, TXDATA				; byte into shift register
			MOV	SUTXST, #0x00				; set TX set to start state

			; Asynchronous Timer2 ; set-up timer2 to transmit 1 byte
			ANL	AUXR,	#(~T2R)				; T2 stop
			ANL	IE2,	#(~ET2)				; disable Timer2 to interrupt
			ORL	AUXR,	#T2x12				; T2 in 1T mode

			MOV	T2L, #(TXBAUD & 0xFF)		; set timer2 reload value
			MOV	T2H, #(TXBAUD >> 8)			;

			ORL	AUXR,	#T2R				; T2 start to run
			ORL	IE2,	#ET2				; enable T2 interrupt
			SETB	EA						; enable interrupts

			CLR	C							; indicate susses

TX_TRANSMIT_EXIT:

			RET

;=======================================================================
;  TIMER 2 INTERRUPT, TX UART TRANSMISSION
;=======================================================================
; NOTE: Not not all configuration have been fully tested

_TIMER2_ISR:
			PUSH	PSW					; resource preservation
			PUSH	ACC
			PUSH	B

			PUSH	DPH					; resource preservation
			PUSH	DPL

			; JB	SWREN, TIMER2_ISR_TXEND	; NOT Transmit Mode
			JNB	STXBSY, TIMER2_ISR_TXEND	; no data to send


			MOV	A, SUTXST				; read state offset from table
			MOV	DPTR, #SWTX_STATE_TABLE
			MOVC	A, @A+DPTR			; 'A' now contains state offset (PC)
			JMP	@A+DPTR					; execute state

TIMER2_ISR_TXEND:						; ALL TX states return here

			POP	DPL						; resource restoration
			POP	DPH

			POP	B
			POP	ACC						; resource restoration
			POP	PSW

			RETI

;-----------------------------------------------------------------------
; TX STATE TABLE
;-----------------------------------------------------------------------
SWTX_STATE_TABLE:						;
	.DB		SWTX_S0  - SWTX_STATE_TABLE	; START bit
	.DB		SWTX_S1  - SWTX_STATE_TABLE	; b0
	.DB		SWTX_S2  - SWTX_STATE_TABLE	; b1
	.DB		SWTX_S3  - SWTX_STATE_TABLE	; b2
	.DB		SWTX_S4  - SWTX_STATE_TABLE	; b3
	.DB		SWTX_S5  - SWTX_STATE_TABLE	; b4
	.DB		SWTX_S6  - SWTX_STATE_TABLE	; b5
	.DB		SWTX_S7  - SWTX_STATE_TABLE	; b6
	.DB		SWTX_S8  - SWTX_STATE_TABLE	; b7
	.DB		SWTX_S9 - SWTX_STATE_TABLE	; stop bit1

;-----------------------------------------------------------------------
;	SWTX_S0: TX START bit state
;-----------------------------------------------------------------------
SWTX_S0:
			; Timer 2 started in Transmit routine

			CLR	SW_TX						; START bit onset edge
			SETB	SWTI					; TX buffer full
			SETB	STXBSY					; transmission in process

			INC	SUTXST						; next state is SWTX_S1

SWTX_S0_END:
			SJMP	TIMER2_ISR_TXEND

;-----------------------------------------------------------------------
;	SWTX_S1 thru SWTX_S9: TX b0..b7 and PARITY/STOP bit
;-----------------------------------------------------------------------
SWTX_S1:									; data bit(0)
SWTX_S2:
SWTX_S3:
SWTX_S4:
SWTX_S5:
SWTX_S6:
SWTX_S7:
SWTX_S8:									; data bit (7)

			MOV	A, TXBIN					; right shift next bit to transmit into Carry
			SETB	C						; shift a STOP bit into MSB
			RRC	A
			MOV	TXBIN,	A					; re-store value
			MOV	SW_TX,	C					; output bit on GPIO pin

			INC	SUTXST						; advance to next state

SWTX_S1_END:
			AJMP	TIMER2_ISR_TXEND

;-----------------------------------------------------------------------
;	SWTX_S9 First STOP bit complete / reset to IDLE
;-----------------------------------------------------------------------
SWTX_S9:

			SETB	SW_TX					; output 1st MARK, stop bit

			; Asynchronous Timer2 END
			ANL	AUXR,	#(~T2R)				; T2 STOP! Stop bit sent.
			ANL	IE2,	#(~ET2)				; disable Timer2 to interrupt

			; stay in this current state until next TX
			SETB	SWTI					; Set SWTI to indicate transmit complete
			CLR	STXBSY						; Clear STXBSY to indicate transmitter available

SWTX_S9_END:
			SJMP	TIMER2_ISR_TXEND


;-----------------------------------------------------------------------
;						END BIT-BANG UART
;-----------------------------------------------------------------------


;=======================================================================
;					END OF PROGRAM
;=======================================================================

